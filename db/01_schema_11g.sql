-- Clean up existing tables and sequences
BEGIN
    FOR t IN (SELECT table_name FROM user_tables WHERE table_name IN 
              ('FEEDBACK', 'BOOKING_SERVICE', 'EMPLOYEE', 'SERVICE', 
               'INVOICE', 'PAYMENT', 'BOOKING', 'ROOM', 'ROOM_TYPE', 'CUSTOMER')) 
    LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
    END LOOP;

    FOR s IN (SELECT sequence_name FROM user_sequences WHERE sequence_name IN
              ('SEQ_CUSTOMER_ID', 'SEQ_ROOMTYPE_ID', 'SEQ_ROOM_ID', 'SEQ_BOOKING_ID',
               'SEQ_PAYMENT_ID', 'SEQ_INVOICE_ID', 'SEQ_SERVICE_ID', 'SEQ_BS_ID',
               'SEQ_EMPLOYEE_ID', 'SEQ_FEEDBACK_ID'))
    LOOP
        EXECUTE IMMEDIATE 'DROP SEQUENCE ' || s.sequence_name;
    END LOOP;
EXCEPTION
    WHEN OTHERS THEN
        NULL;
END;
/

-- Sequences for Auto-Increment Primary Keys (11g Standard)
CREATE SEQUENCE SEQ_CUSTOMER_ID START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_ROOMTYPE_ID START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_ROOM_ID START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_BOOKING_ID START WITH 1001 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_PAYMENT_ID START WITH 5001 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_INVOICE_ID START WITH 9001 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_SERVICE_ID START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_BS_ID START WITH 1 INCREMENT BY 1 NOCACHE;
