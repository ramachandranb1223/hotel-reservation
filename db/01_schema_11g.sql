    CONSTRAINT CHK_BOOKING_TOTAL CHECK (Total_Amount >= 0),
    CONSTRAINT CHK_BOOKING_STATUS CHECK (Status IN ('CONFIRMED', 'CHECKED_IN', 'CHECKED_OUT', 'CANCELLED'))
