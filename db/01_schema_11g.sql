-- 1. TABLE: CUSTOMER
CREATE TABLE CUSTOMER (
    Customer_ID      NUMBER,
    Name             VARCHAR2(100) NOT NULL,
    Phone            VARCHAR2(20)  NOT NULL,
    Email            VARCHAR2(100) NOT NULL,
    Password_Hash    VARCHAR2(255) NOT NULL,
    Role             VARCHAR2(20)  DEFAULT 'CUSTOMER' NOT NULL,
    Address          VARCHAR2(255),
    Date_Of_Birth    DATE,
    Created_At       TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_CUSTOMER PRIMARY KEY (Customer_ID),
    CONSTRAINT UQ_CUSTOMER_EMAIL UNIQUE (Email),
    CONSTRAINT UQ_CUSTOMER_PHONE UNIQUE (Phone),
    CONSTRAINT CHK_CUSTOMER_ROLE CHECK (Role IN ('CUSTOMER', 'ADMIN'))
);

CREATE OR REPLACE TRIGGER TRG_BI_CUSTOMER
BEFORE INSERT ON CUSTOMER FOR EACH ROW
BEGIN
    IF :NEW.Customer_ID IS NULL THEN
        SELECT SEQ_CUSTOMER_ID.NEXTVAL INTO :NEW.Customer_ID FROM DUAL;
    END IF;
END;
/

